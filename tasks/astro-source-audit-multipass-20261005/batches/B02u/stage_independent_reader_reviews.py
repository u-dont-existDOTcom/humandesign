"""Stage fresh source-image fidelity evaluation for draft author windows.
No author context or controller rationale supplied; no writes to source packet.
"""
from pathlib import Path
import json,hashlib,shutil
B=Path(__file__).resolve().parent
OUT=Path.home()/"ai-source-review"
ranges={"B":(369,373),"C":(373,377),"D":(377,381)}
for name,(lo,hi) in ranges.items():
 source=B/f"SOURCE_READER_{name}.json"
 d=json.loads(source.read_text())
 assert d["window"]==name and len(d["units"])>=50
 stage=OUT/f"b02u-independent-{name.lower()}-20261013"
 assert not stage.exists(),"independent stage already exists"
 (stage/"source_images").mkdir(parents=True)
 for page in list(range(lo,hi+1))+[888]:
  n=f"pdf-{page}.png" if page!=888 else "errata-888.png"
  shutil.copy2(B/"evidence"/n,stage/"source_images"/n)
 shutil.copy2(source,stage/"CANDIDATE.json")
 prompt=f"""# Independent original-image documentary source review of B02u window {name}

You are a NEW read-only evaluator, not the author. Parent ChatGPT has already loaded the live UDA/HD AGENTS; do not waste time on web lookups. First read ALL source_images/pdf-{lo}.png through pdf-{hi}.png plus original errata-888.png, in page order. Only AFTER reconstructing the complete source sections independently, open CANDIDATE.json. It was generated by another model and is NOT authoritative. Original 1647 printed text is controlling; later handwritten notes are not assumed to be Lilly's.

Verify EVERY printed heading, separately meaningful historical conditional, planet/house significator and hierarchy, planetary glyph, sign type, appearance/name table, AND/OR, aspect and reception, applying vs separating, change of actor, time/distance qualifier and exception against every unit in CANDIDATE.json. Give a conservative complete omission list, not merely a few sample examples. Explicitly distinguish source print from same-volume errata; original errata PDF888 might address p335–337. If original prints ambiguous or conflicting rules, retain both rather than unifying. Check scope: body PDF{lo}–{hi}, printed {lo-34}–{hi-34}; physical page overlaps an adjacent window, so only review source content, not source ledger counts. Original source alleges thieves/criminal traits, but supplies NO evidence about actual persons; do not draw modern criminal or clinical conclusions.

Return one JSON object only, no Markdown:
{{"window":"{name}","review_type":"FRESH_IMAGE_FIRST_INDEPENDENT_SOURCE_FIDELITY",
"original_pages_read":[{",".join(str(x) for x in range(lo,hi+1))}],
"errata_image_read":true,
"candidate_units_checked":0,
"all_claims_checked":true,
"status":"FINDS_ERROR|NO_MATERIAL_ERRORS_FOUND|REVIEW_INCOMPLETE",
"findings":[{{"id":"F01","severity":"HIGH|MEDIUM|LOW","pdf_page":{lo},"printed_page":{lo-34},"candidate_local_ids":["..."],"original_short_anchor":"short exact phrase/glyph","defect":"what is wrong","narrow_source_correction":"required repair","confidence":"high|medium|low"}}],
"missing_source_units":[{{"pdf_page":{lo},"original_short_anchor":"...","normalized_source_assertion":"..."}}],
"source_ambiguities":[{{"pdf_page":{lo},"description":"...","must_remain_open":true}}],
"source_completeness":"exactly which pages fully read and body continuation caveats"}}.

Do not grade whether astrology works. Keep spelling or glyph uncertain when source illegible. Do not edit any files. The only task is to examine original pages and source-reader candidate for documentary accuracy.
"""
 (stage/"REQUEST.md").write_text(prompt)
 manifest={"batch":"B02u","window":name,"review_type":"INDEPENDENT_IMAGE_FIRST",
           "original_source_sha256":"2cb53e20e122ffc6e47917ba10241f6c49687cd7a4696f3b5db655a2a1aab28b",
           "source_writer_sha256":hashlib.sha256(source.read_bytes()).hexdigest(),
           "files":[{"name":str(f.relative_to(stage)),"sha256":hashlib.sha256(f.read_bytes()).hexdigest(),"bytes":f.stat().st_size} for f in sorted(stage.rglob("*")) if f.is_file()]}
 (B/f"SOURCE_REVIEW_INPUT_{name}.json").write_text(json.dumps(manifest,indent=2)+"\n")
 print(json.dumps({"review":name,"source_pages":hi-lo+1,"draft_units":len(d["units"]),"stage_files":len(manifest["files"])}))
